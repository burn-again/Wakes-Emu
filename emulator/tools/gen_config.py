#!/usr/bin/env python3
"""Generate the emulator's emu_autoconf.h and emu_app_version.h from the firmware's own
firmware/Kconfig, firmware/prj.conf and firmware/VERSION, so the emulator is configured
exactly like the image (no hand-copied CONFIG_ values to drift).

usage: gen_config.py OUT_DIR [SYMBOL=value ...]   e.g. SP1_FRESH=y for the fresh variant
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
FW = os.path.join(ROOT, 'firmware')

# Zephyr/board symbols the firmware reads that are not in its own Kconfig or prj.conf.
# These describe the SP-1's Zephyr build, not choices of Wakes'.
BOARD = {
    'SYS_CLOCK_HW_CYCLES_PER_SEC': '32768',   # nRF52 RTC1, the kernel clock
    'I2C_NRFX_TRANSFER_TIMEOUT': '500',
    'FILE_SYSTEM_MKFS': 'y',
}


def parse_kconfig(path):
    syms = {}
    cur = None
    for raw in open(path, encoding='utf-8'):
        line = raw.split('#', 1)[0].rstrip() if not raw.lstrip().startswith('help') else raw.rstrip()
        m = re.match(r'^\s*(?:menu)?config\s+([A-Z0-9_]+)\s*$', line)
        if m:
            cur = syms.setdefault(m.group(1), {'type': None, 'defaults': []})
            continue
        if cur is None:
            continue
        m = re.match(r'^\s+(bool|int|hex|string)\b', line)
        if m:
            cur['type'] = m.group(1)
            continue
        m = re.match(r'^\s+default\s+(".*?"|\S+)(?:\s+if\s+(.+))?\s*$', line)
        if m:
            cur['defaults'].append((m.group(1), (m.group(2) or '').strip()))
    return syms


def parse_conf(path):
    vals = {}
    for raw in open(path, encoding='utf-8'):
        line = raw.strip()
        if not line or line.startswith('#'):
            continue
        m = re.match(r'^CONFIG_([A-Z0-9_]+)=(.*)$', line)
        if m:
            vals[m.group(1)] = m.group(2).strip()
    return vals


def truthy(vals, expr):
    """Evaluate a Kconfig condition: SYM, !SYM, A && B, A || B (no parentheses needed here)."""
    if not expr:
        return True
    for alt in expr.split('||'):
        ok = True
        for term in alt.split('&&'):
            term = term.strip()
            neg = term.startswith('!')
            name = term.lstrip('!').strip()
            v = vals.get(name, 'n')
            on = v not in ('n', '', '0')
            if on == neg:
                ok = False
                break
        if ok:
            return True
    return False


def resolve(syms, vals):
    changed = True
    passes = 0
    while changed and passes < 20:
        changed = False
        passes += 1
        for name, s in syms.items():
            if name in USER:
                continue
            for val, cond in s['defaults']:
                if truthy(vals, cond):
                    if re.match(r'^[A-Z][A-Z0-9_]*$', val):   # default OTHER_SYMBOL
                        val = vals.get(val, 'n')
                    if vals.get(name) != val:
                        vals[name] = val
                        changed = True
                    break
            else:
                if s['type'] == 'bool' and name not in vals:
                    vals[name] = 'n'
                    changed = True
    return vals


def main():
    out = sys.argv[1]
    overrides = dict(a.split('=', 1) for a in sys.argv[2:])
    os.makedirs(out, exist_ok=True)
    syms = parse_kconfig(os.path.join(FW, 'Kconfig'))
    conf = parse_conf(os.path.join(FW, 'prj.conf'))
    global USER
    USER = set(conf) | set(overrides)
    vals = dict(BOARD)
    vals.update(conf)
    vals.update(overrides)
    vals = resolve(syms, vals)

    lines = ['/* GENERATED by emulator/tools/gen_config.py from firmware/Kconfig + prj.conf. */',
             '#ifndef EMU_AUTOCONF_H', '#define EMU_AUTOCONF_H']
    for name in sorted(vals):
        v = vals[name]
        if v == 'n':
            continue
        if v == 'y':
            lines.append('#define CONFIG_%s 1' % name)
        elif v.startswith('"'):
            lines.append('#define CONFIG_%s %s' % (name, v))
        else:
            lines.append('#define CONFIG_%s %s' % (name, v))
    lines.append('#endif')
    open(os.path.join(out, 'emu_autoconf.h'), 'w').write('\n'.join(lines) + '\n')

    ver = {}
    for raw in open(os.path.join(FW, 'VERSION'), encoding='utf-8'):
        m = re.match(r'^\s*([A-Z_]+)\s*=\s*(\S*)\s*$', raw)
        if m:
            ver[m.group(1)] = m.group(2)
    major, minor, patch = (int(ver.get(k, '0') or 0) for k in
                           ('VERSION_MAJOR', 'VERSION_MINOR', 'PATCHLEVEL'))
    tweak = int(ver.get('VERSION_TWEAK', '0') or 0)
    extra = ver.get('EXTRAVERSION', '')
    vs = '%d.%d.%d' % (major, minor, patch) + ('-' + extra if extra else '')
    av = ['/* GENERATED by emulator/tools/gen_config.py from firmware/VERSION. */',
          '#ifndef EMU_APP_VERSION_H', '#define EMU_APP_VERSION_H',
          '#define APP_VERSION_MAJOR %d' % major,
          '#define APP_VERSION_MINOR %d' % minor,
          '#define APP_PATCHLEVEL %d' % patch,
          '#define APP_TWEAK %d' % tweak,
          '#define APP_VERSION_STRING "%s"' % vs,
          '#define APP_VERSION_EXTENDED_STRING "%s+%d"' % (vs, tweak),
          '#define APP_VERSION_TWEAK_STRING "%s+%d"' % (vs, tweak),
          '#define APP_BUILD_VERSION emu',
          '#define APPVERSION ((%d << 24) | (%d << 16) | (%d << 8) | %d)' % (major, minor, patch, tweak),
          '#endif']
    open(os.path.join(out, 'emu_app_version.h'), 'w').write('\n'.join(av) + '\n')
    print(vs)


USER = set()
if __name__ == '__main__':
    main()
